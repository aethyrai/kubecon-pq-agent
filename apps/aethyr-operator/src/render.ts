import { createHash } from 'node:crypto';
import type { CryptoPolicy, PQPeer, PQTunnel } from '@kubecon-pq-agent/schema';

/**
 * aethyr-tunnel responder config (docs/tunnel in aethyr-node). One responder per PQTunnel:
 * the v1 tunnel maps one listener to one target, so a PQTunnel lists one upstream per listener.
 */
export interface TunnelJson {
  role: 'responder';
  listen: string;
  target: string;
  tenant_did: string;
  allowlist: string;
  tls: { cert: string; key: string; ca: string; server_name: null };
  handshake_version: 2;
  fips_transport: boolean;
  /** Identity level; selects ML-KEM-768 (ML-DSA-65) or ML-KEM-1024 (ML-DSA-87) in the v2 handshake. */
  signature: 'ML-DSA-65' | 'ML-DSA-87';
  rekey_interval: string;
}

export const TENANT_DID = process.env.AETHYR_TENANT_DID ?? 'did:aethyr:org:kubecon-pq-agent';
export const CONFIG_DIR = '/etc/aethyr';
export const TLS_DIR = '/etc/aethyr/tls';

export function upstreamAddress(service: string, port: number, defaultNamespace: string): string {
  const [ns, name] = service.includes('/') ? service.split('/', 2) : [defaultNamespace, service];
  return `${name}.${ns}.svc:${port}`;
}

export function renderTunnel(tunnel: PQTunnel, policy: CryptoPolicy): TunnelJson {
  const up = tunnel.spec.upstreams[0];
  if (!up) throw new Error(`PQTunnel ${tunnel.metadata.name} has no upstream`);
  return {
    role: 'responder',
    listen: `0.0.0.0:${tunnel.spec.listener.port}`,
    target: upstreamAddress(up.service, up.port, tunnel.metadata.namespace ?? 'conf'),
    tenant_did: TENANT_DID,
    allowlist: `${CONFIG_DIR}/peers.txt`,
    tls: {
      cert: `${TLS_DIR}/tls.crt`,
      key: `${TLS_DIR}/tls.key`,
      ca: `${TLS_DIR}/ca.crt`,
      server_name: null,
    },
    handshake_version: 2,
    fips_transport: policy.spec.profile === 'cnsa2',
    signature: policy.spec.signature,
    rekey_interval: policy.spec.rekeyInterval,
  };
}

/** Admitted peers, one DID per line. Peers with no DID yet are skipped. */
export function renderAllowlist(peers: PQPeer[]): string {
  const dids = peers
    .filter((p) => p.status?.admitted === true && typeof p.spec.did === 'string')
    .map((p) => `${p.spec.did} # ${p.metadata.namespace ?? ''}/${p.metadata.name}`)
    .sort();
  return `# generated by aethyr-operator; ${dids.length} admitted peer(s)\n${dids.join('\n')}\n`;
}

export interface GatewayConfig {
  /** ConfigMap data: tunnel-<name>.json per PQTunnel plus peers.txt */
  data: Record<string, string>;
  /** Stable hash; a change rolls the DaemonSet so the gateway reloads. */
  hash: string;
}

export function renderGatewayConfig(
  tunnels: PQTunnel[],
  policies: CryptoPolicy[],
  peers: PQPeer[],
): GatewayConfig {
  const byName = new Map(policies.map((p) => [p.metadata.name, p]));
  const data: Record<string, string> = {};
  for (const t of [...tunnels].sort((a, b) => a.metadata.name.localeCompare(b.metadata.name))) {
    const policy = byName.get(t.spec.policyRef.name);
    if (!policy) continue; // status reports the missing policy; the gateway keeps its last good config
    data[`tunnel-${t.metadata.name}.json`] =
      `${JSON.stringify(renderTunnel(t, policy), null, 2)}\n`;
  }
  data['peers.txt'] = renderAllowlist(peers);
  const hash = createHash('sha256').update(JSON.stringify(data)).digest('hex').slice(0, 16);
  return { data, hash };
}
